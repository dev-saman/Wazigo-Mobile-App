import * as api from '@/api/apis';
import { normalizeError } from '@/api/network';
import type {
  CreateFollowUpPayload,
  FollowUp,
  FollowUpDetail,
  FollowUpOwners,
  UpdateFollowUpPayload,
} from '@/api/types';
import { createAppAsyncThunk } from '@/store/hooks';

import {
  followUpBusy,
  followUpCreating,
  followUpReplaced,
  followUpsFailed,
  followUpsLoaded,
  followUpsLoading,
} from './followUpsSlice';

/** CHAT-28. Open ones first, then the last 20 closed; the server orders them. */
export const loadFollowUps = createAppAsyncThunk<void, { conversationId: string }>(
  'followUps/load',
  async ({ conversationId }, { dispatch, rejectWithValue }) => {
    dispatch(followUpsLoading({ conversationId }));
    try {
      const { data } = await api.getFollowUps(conversationId);
      dispatch(
        followUpsLoaded({
          conversationId,
          items: Array.isArray(data?.follow_ups) ? data.follow_ups : [],
          canCreate: data?.can_create === true,
          limit: data?.limit ?? null,
        }),
      );
      return;
    } catch (error) {
      const apiError = normalizeError(error);
      dispatch(followUpsFailed({ conversationId, error: apiError }));
      return rejectWithValue(apiError);
    }
  },
);

/** CHAT-29. Without `follow_ups.assign` the list holds only the signed-in person. */
export const loadFollowUpOwners = createAppAsyncThunk<
  FollowUpOwners['owners'],
  { conversationId: string }
>('followUps/owners', async ({ conversationId }, { rejectWithValue }) => {
  try {
    const { data } = await api.getFollowUpOwners(conversationId);
    return Array.isArray(data?.owners) ? data.owners : [];
  } catch (error) {
    return rejectWithValue(normalizeError(error));
  }
});

/**
 * CHAT-30. The key is generated by the caller, once per tap, so a retry after
 * a timeout replays the first answer instead of creating a second follow-up.
 * Reusing a key with a different body is a 409 and is the caller's bug.
 */
export const createFollowUp = createAppAsyncThunk<
  FollowUp,
  { conversationId: string; payload: CreateFollowUpPayload }
>('followUps/create', async ({ conversationId, payload }, { dispatch, rejectWithValue }) => {
  dispatch(followUpCreating({ conversationId, creating: true }));
  try {
    const { data } = await api.createFollowUp(conversationId, payload);
    if (data) dispatch(followUpReplaced({ conversationId, followUp: data }));
    else await dispatch(loadFollowUps({ conversationId }));
    return data as FollowUp;
  } catch (error) {
    const apiError = normalizeError(error);
    dispatch(followUpsFailed({ conversationId, error: apiError }));
    return rejectWithValue(apiError);
  }
});

/** CHAT-31. Only while open, acknowledged or snoozed. */
export const updateFollowUp = createAppAsyncThunk<
  void,
  { conversationId: string; followUpId: number; payload: UpdateFollowUpPayload }
>(
  'followUps/update',
  async ({ conversationId, followUpId, payload }, { dispatch, rejectWithValue }) => {
    dispatch(followUpBusy({ conversationId, followUpId }));
    try {
      const { data } = await api.updateFollowUp(followUpId, payload);
      if (data) dispatch(followUpReplaced({ conversationId, followUp: data }));
      return;
    } catch (error) {
      const apiError = normalizeError(error);
      dispatch(followUpsFailed({ conversationId, error: apiError }));
      // 409: this phone's copy is behind. Re-read rather than resend with the
      // version the server has just rejected.
      if (apiError.code === 'CONFLICT') void dispatch(loadFollowUps({ conversationId }));
      return rejectWithValue(apiError);
    }
  },
);

export type FollowUpTransition = 'acknowledge' | 'snooze' | 'complete' | 'cancel';

type TransitionPayload = { version: number; until?: string; reason?: string; note?: string };

/**
 * CHAT-32. Acknowledge, snooze, complete or cancel - all optimistic-locked on
 * `version`, and all answered with the row as the server now has it.
 *
 * Nothing is applied locally first: a transition the server refuses (422
 * `invalid_transition`) must not flicker as if it had worked.
 */
export const transitionFollowUp = createAppAsyncThunk<
  void,
  {
    conversationId: string;
    followUpId: number;
    transition: FollowUpTransition;
    payload: TransitionPayload;
  }
>(
  'followUps/transition',
  async ({ conversationId, followUpId, transition, payload }, { dispatch, rejectWithValue }) => {
    dispatch(followUpBusy({ conversationId, followUpId }));
    try {
      const call =
        transition === 'acknowledge'
          ? api.acknowledgeFollowUp(followUpId, { version: payload.version })
          : transition === 'snooze'
            ? api.snoozeFollowUp(followUpId, {
                version: payload.version,
                until: payload.until ?? '',
                reason: payload.reason ?? '',
              })
            : transition === 'complete'
              ? api.completeFollowUp(followUpId, {
                  version: payload.version,
                  note: payload.note ?? '',
                })
              : api.cancelFollowUp(followUpId, {
                  version: payload.version,
                  reason: payload.reason ?? '',
                });

      const { data } = await call;
      if (data) dispatch(followUpReplaced({ conversationId, followUp: data }));
      return;
    } catch (error) {
      const apiError = normalizeError(error);
      dispatch(followUpsFailed({ conversationId, error: apiError }));
      if (apiError.code === 'CONFLICT') void dispatch(loadFollowUps({ conversationId }));
      return rejectWithValue(apiError);
    }
  },
);

/**
 * CHAT-33. The history of one follow-up: who changed it, when and why.
 *
 * It is a detail sheet nobody needs to open, so it is read on demand and kept
 * by the screen rather than in the slice - there is nothing to keep in sync.
 */
export const loadFollowUpDetail = createAppAsyncThunk<FollowUpDetail, { followUpId: number }>(
  'followUps/detail',
  async ({ followUpId }, { rejectWithValue }) => {
    try {
      const { data } = await api.getFollowUp(followUpId);
      return {
        follow_up: data?.follow_up as FollowUp,
        events: Array.isArray(data?.events) ? data.events : [],
      };
    } catch (error) {
      return rejectWithValue(normalizeError(error));
    }
  },
);
